#!/usr/bin/env node
// Copies drizzle/*.sql (in _journal.json order) into lib/db/migrations.gen.ts so the server bundle
// carries its migrations: serverless output tracing does not reliably ship a folder read at runtime.
// Usage: node lib/db/embed-migrations.mjs          (write)
//        node lib/db/embed-migrations.mjs --check  (exit 1 when the embedded copy is stale)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const folder = join(root, "drizzle");
const target = join(root, "lib", "db", "migrations.gen.ts");

export function render() {
  const journal = JSON.parse(readFileSync(join(folder, "meta", "_journal.json"), "utf8"));
  const migrations = journal.entries.map((entry) => {
    const sql = readFileSync(join(folder, `${entry.tag}.sql`), "utf8");
    const statements = sql
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean);
    return { tag: entry.tag, hash: createHash("sha256").update(sql).digest("hex"), statements };
  });
  return [
    "// GENERATED by lib/db/embed-migrations.mjs from drizzle/. Do not edit by hand.",
    "export interface EmbeddedMigration { tag: string; hash: string; statements: string[] }",
    "",
    `export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};`,
    "",
  ].join("\n");
}

const out = render();
if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("lib/db/migrations.gen.ts is stale: run node lib/db/embed-migrations.mjs");
    process.exit(1);
  }
  console.log("migrations embed up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
